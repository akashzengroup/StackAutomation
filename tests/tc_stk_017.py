def _send_command(conn, command):
    """
    Send a command using the existing SwitchConnection object.
    """

    if conn is None:
        return ""

    if hasattr(conn, "send_command"):
        return conn.send_command(command)

    if hasattr(conn, "execute"):
        return conn.execute(command)

    if hasattr(conn, "command"):
        return conn.command(command)

    if hasattr(conn, "send"):
        result = conn.send(command)

        if result is None:
            return ""

        return str(result)

    raise AttributeError(
        "SwitchConnection does not provide a supported "
        "command execution method."
    )


def _read_available(conn):
    """
    Try to read currently available data from the connection.
    """

    if conn is None:
        return ""

    methods = [
        "read",
        "read_all",
        "read_output",
        "receive",
        "recv",
    ]

    for method_name in methods:

        method = getattr(conn, method_name, None)

        if method is None:
            continue

        try:
            result = method()

            if result is None:
                return ""

            return str(result)

        except TypeError:
            continue

        except Exception:
            continue

    return ""


def _run_command(conn, command):
    """
    Normal command execution.
    """

    try:
        result = _send_command(conn, command)

        if result is None:
            return ""

        return str(result)

    except Exception as exc:
        print(f"Command failed: {command}")
        print(f"Error: {exc}")
        return ""


