# PAGINATED COMMAND SUPPORT
# =========================================================

def _contains_pager(output):
    """
    Detect ROS7 pager text.
    """

    if not output:
        return False

    patterns = [
        r"More:\s*<space>",
        r"More:\s*<space>\s*,\s*Quit:",
        r"One line:\s*<return>",
        r"Quit:\s*q\s+or\s+CTRL\+Z",
    ]

    for pattern in patterns:

        if re.search(
            pattern,
            output,
            flags=re.IGNORECASE
        ):
            return True

    return False


def _remove_pager_lines(output):
    """
    Remove pager prompt text from command output.
    """

    if not output:
        return ""

    lines = output.splitlines()
    cleaned = []

    for line in lines:

        stripped = line.strip()

        if not stripped:
            cleaned.append(line)
            continue

        if re.search(
            r"More:\s*<space>",
            stripped,
            flags=re.IGNORECASE
        ):
            continue

        if re.search(
            r"Quit:\s*q\s+or\s+CTRL\+Z",
            stripped,
            flags=re.IGNORECASE
        ):
            continue

        if re.search(
            r"One line:\s*<return>",
            stripped,
            flags=re.IGNORECASE
        ):
            continue

        cleaned.append(line)

    return "\n".join(cleaned)


def _send_space_for_pager(conn):
    """
    Continue to the next ROS7 pager page.
    """

    if conn is None:
        return ""

    methods = [
        "send",
        "write",
        "send_command",
    ]

    for method_name in methods:

        method = getattr(conn, method_name, None)

        if method is None:
            continue

        try:

            result = method(" ")

            if result is None:
                return ""

            return str(result)

        except Exception:
            continue

    return ""


def _run_paged_command(
    conn,
    command,
    timeout=30,
    max_pages=MAX_PAGES
):
    """
    Execute a command and automatically continue through ROS7
    pager pages.

    No output is fabricated. Every returned log line comes
    from the switch connection.
    """

    if conn is None:
        return ""

    collected = []

    try:

        first_output = _send_command(
            conn,
            command
        )

        if first_output:
            collected.append(str(first_output))

        start_time = time.time()
        pages = 1

        while pages < max_pages:

            current = "\n".join(collected)

            if not _contains_pager(current):
                break

            if time.time() - start_time > timeout:

                print(
                    f"WARNING: Pager timeout while running "
                    f"'{command}'."
                )

                break

            page_output = _send_space_for_pager(
                conn
            )

            if page_output:
                collected.append(
                    str(page_output)
                )

            pages += 1

            time.sleep(0.15)

        result = "\n".join(collected)

        return _remove_pager_lines(result)

    except Exception as exc:

        print(
            f"WARNING: Failed to read paginated command "
            f"'{command}': {exc}"
        )

        return "\n".join(collected)


