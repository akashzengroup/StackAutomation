def _test_member_join(master_conn):

    _print_header(
        "TC-STK-017.1 - MEMBER JOIN LOG VERIFICATION"
    )

    print(
        "This test verifies the REAL switch-generated logs "
        "when a stack member joins/reconnects."
    )

    print(
        "No fake log messages are generated by this testcase."
    )

    # -----------------------------------------------------
    # Baseline
    # -----------------------------------------------------

    print()
    print("Reading current stack state...")

    before_stack_output, initial_members = (
        _get_stack_state(
            master_conn
        )
    )

    _display_stack_members(
        initial_members,
        "Initial Stack Members"
    )

    print()
    print(
        "Capturing current switch logging buffer..."
    )

    before_logs = _get_logging(
        master_conn
    )

    # -----------------------------------------------------
    # User action
    # -----------------------------------------------------

    _wait_for_user(
        "\nDisconnect/reconnect the stack member as required, "
        "then press ENTER to continue..."
    )

    _wait_seconds(
        STACK_WAIT_TIME,
        "Waiting for stack/member event logs..."
    )

    # -----------------------------------------------------
    # Read current state
    # -----------------------------------------------------

    after_stack_output, members_after = (
        _get_stack_state(
            master_conn
        )
    )

    _display_stack_members(
        members_after,
        "Stack Members After Member Join"
    )

    print()
    print("Reading NEW switch logs...")

    after_logs = _get_logging(
        master_conn
    )

    new_logs = _get_new_log_lines(
        before_logs,
        after_logs
    )

    matches = _find_matching_log_lines(
        "\n".join(new_logs),
        MEMBER_JOIN_PATTERNS
    )

    # -----------------------------------------------------
    # Validation
    # -----------------------------------------------------

    print()
    print(
        f"Initial Unit-IDs : {initial_members}"
    )

    print(
        f"Current Unit-IDs : {members_after}"
    )

    new_units = sorted(
        set(members_after) -
        set(initial_members)
    )

    if new_units:

        print(
            f"New Unit-ID(s) detected: {new_units}"
        )

    else:

        print(
            "No new Unit-ID detected."
        )

        print(
            "This is allowed because the member may have "
            "reconnected using an existing Unit-ID."
        )

    stack_state_valid = True

    if initial_members and members_after:

        missing_units = sorted(
            set(initial_members) -
            set(members_after)
        )

        if missing_units:

            print(
                f"WARNING: Existing Unit-ID(s) currently "
                f"missing: {missing_units}"
            )

            stack_state_valid = False

    log_pass = bool(matches)

    _display_ros7_log_result(
        "MEMBER JOIN LOG",
        matches,
        passed=log_pass
    )

    if log_pass and stack_state_valid:

        print(
            "MEMBER JOIN RESULT : PASS"
        )

        return True

    if log_pass and not stack_state_valid:

        print(
            "MEMBER JOIN RESULT : PASS "
            "(REAL JOIN/RECOVERY LOG DETECTED)"
        )

        return True

    print(
        "MEMBER JOIN RESULT : FAIL"
    )

    return False


