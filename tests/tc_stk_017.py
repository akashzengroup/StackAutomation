def _parse_stack_members(output):
    """
    Parse Unit IDs from 'show stack'.

    Supports multiple common formats.
    """

    members = set()

    if not output:
        return sorted(members)

    lines = output.splitlines()

    for line in lines:

        stripped = line.strip()

        if not stripped:
            continue

        if stripped.lower().startswith(
            (
                "show stack",
                "unit",
                "role",
                "mac",
                "state",
                "----",
                "more:",
            )
        ):
            continue

        # Example:
        # 1 MASTER ...
        # 2 BACKUP ...
        match = re.match(
            r"^\s*(\d{1,2})\s+"
            r"(?:MASTER|BACKUP|MEMBER|STANDBY|ACTIVE)\b",
            stripped,
            flags=re.IGNORECASE
        )

        if match:

            try:
                members.add(
                    int(match.group(1))
                )

            except ValueError:
                pass

            continue

        # Example:
        # UNIT ID 3
        match = re.search(
            r"\bUNIT\s+ID\s*[:=]?\s*(\d{1,2})\b",
            stripped,
            flags=re.IGNORECASE
        )

        if match:

            try:
                members.add(
                    int(match.group(1))
                )

            except ValueError:
                pass

            continue

        # Example:
        # Unit 3
        match = re.search(
            r"\bUNIT\s+(\d{1,2})\b",
            stripped,
            flags=re.IGNORECASE
        )

        if match:

            try:

                unit_id = int(
                    match.group(1)
                )

                if 1 <= unit_id <= 64:
                    members.add(unit_id)

            except ValueError:
                pass

    return sorted(members)


def _display_stack_members(
    members,
    title="Stack Members"
):
    print()
    print(title)
    print("-" * 50)

    if not members:
        print("No stack members detected.")
        return

    for unit_id in members:
        print(f"  Unit-ID {unit_id}")


def _get_stack_state(master_conn):
    """
    Read complete paginated show stack output.
    """

    output = _run_paged_command(
        master_conn,
        SHOW_STACK_COMMAND,
        timeout=30
    )

    members = _parse_stack_members(
        output
    )

    return output, members


