def _print_header(title):
    print()
    print("=" * 70)
    print(title)
    print("=" * 70)


def _wait_seconds(seconds, message=None):
    if message:
        print(message)

    for remaining in range(seconds, 0, -1):
        print(
            f"\rWaiting: {remaining:>3} seconds",
            end="",
            flush=True
        )
        time.sleep(1)

    print()


def _wait_for_user(message):
    print()
    input(message)


