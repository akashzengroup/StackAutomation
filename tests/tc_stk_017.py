def _get_logging(master_conn):
    """
    Read the COMPLETE switch logging buffer.
    """

    output = _run_paged_command(
        master_conn,
        SHOW_LOG_COMMAND,
        timeout=60
    )

    return output


def _normalize_log(line):
    """
    Normalize a log line for comparison/searching.
    """

    if line is None:
        return ""

    value = str(line)

    value = value.replace(
        "\r",
        " "
    )

    value = re.sub(
        r"\s+",
        " ",
        value
    )

    return value.strip()


def _clean_log_lines(output):
    """
    Convert logging output to normalized non-empty lines.
    """

    if not output:
        return []

    result = []

    for line in output.splitlines():

        normalized = _normalize_log(
            line
        )

        if not normalized:
            continue

        if re.search(
            r"More:\s*<space>",
            normalized,
            flags=re.IGNORECASE
        ):
            continue

        result.append(normalized)

    return result


def _get_new_log_lines(
    before_output,
    after_output
):
    """
    Return only log lines that appeared after the baseline.

    Multiset-style removal is used so duplicate switch log
    messages are handled correctly.
    """

    before_lines = _clean_log_lines(
        before_output
    )

    after_lines = _clean_log_lines(
        after_output
    )

    remaining_before = {}

    for line in before_lines:

        remaining_before[line] = (
            remaining_before.get(
                line,
                0
            ) + 1
        )

    new_lines = []

    for line in after_lines:

        count = remaining_before.get(
            line,
            0
        )

        if count > 0:

            remaining_before[line] = (
                count - 1
            )

        else:

            new_lines.append(line)

    return new_lines


def _find_log_signatures(
    log_output,
    patterns
):
    """
    Find real switch-generated log lines matching
    supplied ROS7 regular expressions.
    """

    matches = []

    if not log_output:
        return matches

    lines = _clean_log_lines(
        log_output
    )

    compiled_patterns = []

    for pattern in patterns:

        try:

            compiled_patterns.append(
                re.compile(
                    pattern,
                    flags=re.IGNORECASE
                )
            )

        except re.error as exc:

            print(
                f"WARNING: Invalid log pattern "
                f"'{pattern}': {exc}"
            )

    for line in lines:

        for pattern in compiled_patterns:

            if pattern.search(line):

                if line not in matches:
                    matches.append(line)

                break

    return matches


def _find_matching_log_lines(
    log_output,
    patterns
):
    """
    Alias/helper for readability.
    """

    return _find_log_signatures(
        log_output,
        patterns
    )


def _display_ros7_log_result(
    title,
    matched_lines,
    passed=True
):
    print()
    print(title)
    print("-" * 70)

    if matched_lines:

        print(
            "REAL ROS7 SWITCH LOG MESSAGES FOUND:"
        )

        for line in matched_lines:
            print(f"  {line}")

    else:

        print(
            "No matching ROS7 switch-generated "
            "log message was found."
        )

    print()

    if passed:
        print(f"{title} : PASS")
    else:
        print(f"{title} : FAIL")


