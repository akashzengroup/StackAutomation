def _display_final_result(results):

    _print_header(
        "TC-STK-017 FINAL RESULT"
    )

    event_names = [
        "Member Join",
        "Member Leave",
        "MASTER Change",
        "Stack Link Failure",
        "Upgrade",
    ]

    passed_count = 0

    for index, name in enumerate(
        event_names
    ):

        result = False

        if index < len(results):
            result = bool(
                results[index]
            )

        status = (
            "PASS"
            if result
            else "FAIL"
        )

        print(
            f"{index + 1}. "
            f"{name:<25} : {status}"
        )

        if result:
            passed_count += 1

    print()

    print(
        f"Passed: {passed_count}/"
        f"{len(event_names)}"
    )

    if passed_count == len(event_names):

        print()
        print(
            "TC-STK-017 RESULT : PASS"
        )

        return True

    print()
    print(
        "TC-STK-017 RESULT : FAIL"
    )

    return False


